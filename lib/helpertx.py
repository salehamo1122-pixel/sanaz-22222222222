# ============= تابع کمکی برای نمایش راهنما =============
async def show_help(event, page=1):
    """نمایش راهنما با صفحه‌بندی"""
    if event.sender_id != admin_user_id:
        return
    
    help_functions = {
        1: help_1,
        2: help_2,
        3: help_3,
        4: help_4
    }
    
    if page in help_functions:
        await help_functions[page](event)
    else:
        await event.edit("**❈ صفحه راهنما پیدا نشد. از /help 1 تا 4 استفاده کنید.**")
